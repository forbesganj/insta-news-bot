"""Sound design: original synthesised music pad, whoosh transitions, voice-ducking mix, loudness normalisation.

Everything here is generated by ffmpeg itself, so there are no licence or copyright questions. If you add your own
royalty-free tracks to assets/music/ they are used instead of the synthesised pad.
"""
from __future__ import annotations

import hashlib
import logging
from pathlib import Path

from ..settings import Settings
from .util import MediaError, run

log = logging.getLogger(__name__)

AUDIO_EXT = {".mp3", ".m4a", ".wav", ".ogg", ".flac"}
# (frequencies in Hz) simple warm triads/seventh chords; one is picked per story for variety
CHORDS = [
    (110.00, 130.81, 164.81, 220.00),   # A minor
    (130.81, 164.81, 196.00, 261.63),   # C major
    (87.31, 130.81, 174.61, 220.00),    # F major
    (98.00, 123.47, 146.83, 196.00),    # G major
]


def _hash_int(text: str) -> int:
    return int(hashlib.sha1(text.encode()).hexdigest()[:8], 16)


def make_whoosh(path: Path) -> Path:
    run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i",
         "anoisesrc=color=pink:d=0.5:amplitude=0.6:sample_rate=44100",
         "-af", "highpass=f=450,lowpass=f=7000,afade=t=in:d=0.14,afade=t=out:st=0.2:d=0.3,volume=0.9",
         "-ac", "2", str(path)])
    return path


def make_pad(path: Path, seconds: float, seed: str) -> Path:
    """Soft evergreen pad with a very gentle pulse. Original, royalty-free by construction."""
    freqs = CHORDS[_hash_int(seed) % len(CHORDS)]
    dur = f"{seconds + 1.0:.2f}"
    cmd = ["ffmpeg", "-y", "-loglevel", "error"]
    for f in freqs:
        cmd += ["-f", "lavfi", "-i", f"sine=f={f}:d={dur}:sample_rate=44100"]
    cmd += ["-f", "lavfi", "-i", f"sine=f=55:d={dur}:sample_rate=44100"]
    n = len(freqs)
    graph = (f"{''.join(f'[{i}:a]' for i in range(n))}amix=inputs={n}:normalize=0,volume=0.35,"
             f"tremolo=f=0.18:d=0.35,lowpass=f=1500[pad];"
             f"[{n}:a]tremolo=f=1.8:d=1.0,volume=0.30,lowpass=f=140[pulse];"
             f"[pad][pulse]amix=inputs=2:normalize=0,aformat=channel_layouts=stereo,"
             f"afade=t=in:d=1.2,afade=t=out:st={max(seconds - 1.2, 0):.2f}:d=1.2[out]")
    cmd += ["-filter_complex", graph, "-map", "[out]", str(path)]
    run(cmd)
    return path


def pick_music(settings: Settings, story_id: str) -> Path | None:
    mode = str(settings.get("media.music_mode", "auto")).lower()
    if mode == "off":
        return None
    folder = settings.root / str(settings.get("media.music_dir", "assets/music"))
    tracks = sorted(p for p in folder.glob("*") if p.suffix.lower() in AUDIO_EXT) if folder.exists() else []
    if tracks and mode in ("auto", "files"):
        return tracks[_hash_int(story_id) % len(tracks)]
    return None


def mix_audio(voice: Path, total: float, beat_starts: list[float], music: Path | None, voice_is_silent: bool,
              settings: Settings, work_dir: Path, out: Path) -> Path:
    """voice + whoosh effects + ducked music -> loudness-normalised stereo WAV of exactly `total` seconds."""
    sfx_on = bool(settings.get("media.sfx", True))
    vol_music = float(settings.get("media.music_volume", 0.11))
    if voice_is_silent:
        vol_music = max(vol_music * 3.0, 0.3)
    starts = [t for t in beat_starts[1:] if t < total - 0.6] if sfx_on else []

    inputs: list[str] = ["-i", str(voice)]
    graph: list[str] = []
    voice_label = "[0:a]"
    idx = 1
    if starts:
        whoosh = make_whoosh(work_dir / "whoosh.wav")
        inputs += ["-i", str(whoosh)]
        w_idx = idx
        idx += 1
        sfx_vol = float(settings.get("media.sfx_volume", 0.45))
        if len(starts) == 1:
            graph.append(f"[{w_idx}:a]adelay={int(starts[0] * 1000)}|{int(starts[0] * 1000)},volume={sfx_vol}[s0]")
        else:
            split = "".join(f"[w{i}]" for i in range(len(starts)))
            graph.append(f"[{w_idx}:a]asplit={len(starts)}{split}")
            for i, t in enumerate(starts):
                ms = int(t * 1000)
                graph.append(f"[w{i}]adelay={ms}|{ms},volume={sfx_vol}[s{i}]")
        labels = "".join(f"[s{i}]" for i in range(len(starts)))
        graph.append(f"[0:a]{labels}amix=inputs={len(starts) + 1}:normalize=0:duration=longest[vs]")
        voice_label = "[vs]"

    final_label = voice_label
    if music is not None:
        inputs += ["-stream_loop", "-1", "-i", str(music)]
        m_idx = idx
        if voice_is_silent:
            graph.append(f"{voice_label}anull[v_out]")
        else:
            graph.append(f"{voice_label}asplit=2[v_out][v_side]")
        graph.append(f"[{m_idx}:a]aformat=channel_layouts=stereo,volume={vol_music},"
                     f"afade=t=in:d=1.0,afade=t=out:st={max(total - 1.5, 0):.2f}:d=1.5[m]")
        if voice_is_silent:
            graph.append("[m]anull[md]")
        else:
            graph.append("[m][v_side]sidechaincompress=threshold=0.02:ratio=9:attack=15:release=350[md]")
        graph.append("[v_out][md]amix=inputs=2:normalize=0:duration=longest[mix]")
        final_label = "[mix]"
    norm = float(settings.get("media.loudness", -15))
    if voice_is_silent and music is None and not starts:
        graph.append(f"{final_label}anull[out]")
    else:
        graph.append(f"{final_label}loudnorm=I={norm}:TP=-1.5:LRA=11,atrim=0:{total:.3f},asetpts=PTS-STARTPTS[out]")
    cmd = ["ffmpeg", "-y", "-loglevel", "error", *inputs, "-filter_complex", ";".join(graph), "-map", "[out]",
           "-ar", "44100", "-ac", "2", "-t", f"{total:.3f}", str(out)]
    try:
        run(cmd, cwd=work_dir)
    except MediaError as exc:
        log.warning("audio mix failed (%s); using the plain voice track", str(exc)[:200])
        run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(voice), "-af", "apad", "-t", f"{total:.3f}",
             "-ar", "44100", "-ac", "2", str(out)], cwd=work_dir)
    return out
